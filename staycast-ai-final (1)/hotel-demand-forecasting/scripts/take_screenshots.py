"""Capture dashboard screenshots for the report.  Needs the API (8000) and Streamlit (8501) running.

    python scripts/take_screenshots.py
"""
import sys
from pathlib import Path

from playwright.sync_api import sync_playwright

OUT = Path(__file__).resolve().parents[1] / "reports" / "screenshots"
OUT.mkdir(parents=True, exist_ok=True)
PAGES = ["Executive Overview", "Forecast Intelligence", "Room Category Analytics", "Model Performance Lab",
         "Prediction Explorer", "Explainable AI", "Data & Model Health"]
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8501"

with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={"width": 1440, "height": 900}, device_scale_factor=1)
    for i, name in enumerate(PAGES, 1):
        page.goto(f"{BASE}/?page={name.replace(' ', '%20').replace('&', '%26')}")
        page.wait_for_selector("h1", timeout=60000)
        page.wait_for_timeout(2500)
        if name == "Prediction Explorer":
            page.get_by_role("button", name="Generate forecast").click()
            page.wait_for_selector("text=Forecast generated by", timeout=60000)
            page.wait_for_timeout(2500)
        page.screenshot(path=str(OUT / f"{i}_{name.lower().replace(' & ', '_').replace(' ', '_')}.png"), full_page=True)
        print("saved", name)
    browser.close()
